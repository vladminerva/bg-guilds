"""Build BGGuilds_Data/Data.lua from crawled guild roster JSONs.
Usage: python3 -I build_data.py <out_Data.lua> <roster_dir> [<roster_dir> ...]
Later dirs win when the same character appears twice (pass oldest first).
"""
import json, sys, pathlib, datetime

def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'

def main(out, dirs):
    chars = {}   # (realm, name) -> guild
    for d in dirs:
        for f in sorted(pathlib.Path(d).glob("*.json")):
            if f.name.startswith("_"):
                continue
            g = json.loads(f.read_text())
            for m in g.get("roster", []):
                chars[(g["realm"], m["name"])] = g["name"]
    guilds = sorted(set(chars.values()))
    gidx = {g: i + 1 for i, g in enumerate(guilds)}
    realms = sorted({r for r, _ in chars})
    stamp = datetime.date.today().isoformat()
    lines = ["-- Generated by crawl/build_data.py. Do not edit by hand.",
             "BGGuilds_DB = {",
             f"  version = {lua_str(stamp)},",
             f"  count = {len(chars)},",
             "  guilds = {"]
    lines += [f"    {lua_str(g)}," for g in guilds]
    lines += ["  },", "  realms = {}", "}", "local g = BGGuilds_DB.realms"]
    # One table per realm, in chunks, to stay far below Lua 5.1 constant limits as the DB grows.
    for r in realms:
        names = sorted(n for rr, n in chars if rr == r)
        lines.append(f"g[{lua_str(r)}] = {{}}")
        for i in range(0, len(names), 5000):
            lines.append("do local t = g[%s]" % lua_str(r))
            lines += [f"t[{lua_str(n)}]={gidx[chars[(r, n)]]}" for n in names[i:i + 5000]]
            lines.append("end")
    pathlib.Path(out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{out}: {len(chars)} characters, {len(guilds)} guilds, realms {realms}, version {stamp}")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2:])
